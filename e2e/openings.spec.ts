import { expect, test, type Page } from '@playwright/test'

async function openEditor(page: Page, es: boolean) {
  await page.goto('/')
  await page.getByRole('button', { name: es ? 'Crear un proyecto' : 'Create a project', exact: true }).click()
  await page.locator('#projectName').fill('Aberturas')
  await page.locator('#roomName').fill('Dormitorio')
  await page.getByRole('button', { name: es ? 'Continuar' : 'Continue', exact: true }).click()
  await page.locator('#width').fill('4.2')
  await page.locator('#depth').fill('3.15')
  await page.getByRole('button', { name: es ? 'Crear y guardar' : 'Create and save', exact: true }).click()
  await page.getByRole('button', { name: es ? 'Abrir plano 2D' : 'Open 2D plan', exact: true }).click()
  await expect(page.locator('.canvas-surface canvas')).toBeVisible()
}
async function savedJson(page: Page): Promise<string> {
  return page.evaluate(() => new Promise<string>((resolve, reject) => {
    const request = indexedDB.open('cuartos-local')
    request.onerror = () => reject(request.error)
    request.onsuccess = () => {
      const db = request.result, read = db.transaction('projects').objectStore('projects').getAll()
      read.onsuccess = () => { db.close(); resolve(read.result[0].json) }
      read.onerror = () => { db.close(); reject(read.error) }
    }
  }))
}
const save = (page: Page, es: boolean) => page.getByRole('button', { name: es ? 'Guardar abertura' : 'Save opening', exact: true }).click()
const door = (page: Page, es: boolean, n = 1) => page.getByRole('button', { name: new RegExp(`^${es ? 'Puerta' : 'Door'} ${n} `) })
const windowItem = (page: Page, es: boolean) => page.getByRole('button', { name: new RegExp(`^${es ? 'Ventana' : 'Window'} 2 `) })

async function doorForm(page: Page, es: boolean) {
  await page.getByRole('button', { name: es ? 'Añadir puerta' : 'Add door', exact: true }).click()
  await page.locator('#opening-offset').fill('0.5')
  await page.locator('#opening-width').fill('0.9')
  await page.locator('#opening-height').fill('2.1')
}

test('add, select on canvas, edit, cancel, reopen and delete wall openings', async ({ page, context }, info) => {
  const es = info.project.name === 'phone', errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await openEditor(page, es)
  const original = JSON.parse(await savedJson(page))
  await doorForm(page, es)
  await page.locator('#opening-unit').selectOption('cm')
  await expect(page.locator('#opening-width')).toHaveValue('90')
  await page.locator('#opening-offset').fill('50')
  await save(page, es)
  await expect(door(page, es)).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: es ? 'Añadir ventana' : 'Add window', exact: true }).click()
  await page.locator('#opening-wallId').selectOption({ index: 1 })
  await page.locator('#opening-unit').selectOption('cm')
  for (const [field, value] of Object.entries({ offset: '60', width: '120', height: '100', sillHeight: '90' })) await page.locator(`#opening-${field}`).fill(value)
  await save(page, es)
  await expect(windowItem(page, es)).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Dormitorio', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.screenshot({ path: `test-results/openings-${info.project.name}.png`, fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const surface = page.locator('.canvas-surface')
  // Select the middle of the actual door gap, using the same world dimensions.
  const size = await surface.evaluate(el => ({ width: el.clientWidth, height: el.clientHeight }))
  const pad = Math.min(64, size.width * .18, size.height * .18)
  const scale = Math.min((size.width - 2 * pad) / 4.2, (size.height - 2 * pad) / 3.15)
  await surface.click({ position: { x: size.width / 2 + (.95 - 2.1) * scale, y: size.height / 2 - 1.575 * scale } })
  await expect(door(page, es)).toHaveAttribute('aria-pressed', 'true')
  await windowItem(page, es).click()
  await page.getByRole('button', { name: es ? 'Editar abertura' : 'Edit opening', exact: true }).click()
  for (const [field, value] of Object.entries({ offset: '0.7', width: '1.4', height: '1', sillHeight: '1.1' })) await page.locator(`#opening-${field}`).fill(value)
  const form = page.locator('.opening-form-panel')
  await form.screenshot({ path: `test-results/opening-form-${info.project.name}.png` })
  await save(page, es)
  await expect(form).toHaveCount(0)
  const edited = JSON.parse(await savedJson(page))
  expect(edited.rooms).toEqual(original.rooms)
  expect(edited.furniture).toEqual(original.furniture)
  expect(edited.openings[0]).toMatchObject({ type: 'door', offset: .5, width: .9, height: 2.1, sillHeight: 0 })
  expect(edited.openings[1]).toMatchObject({ type: 'window', offset: .7, width: 1.4, height: 1, sillHeight: 1.1 })
  expect(edited.openings[1].wallId).not.toBe(edited.openings[0].wallId)
  const reopened = await context.newPage()
  await page.close()
  await reopened.route('**/*', route => new URL(route.request().url()).origin === 'http://127.0.0.1:4173' ? route.continue() : route.abort())
  await reopened.goto('/')
  await reopened.getByRole('button', { name: /Aberturas/ }).click()
  await reopened.getByRole('button', { name: es ? 'Abrir plano 2D' : 'Open 2D plan', exact: true }).click()
  await door(reopened, es).click()
  await reopened.getByRole('button', { name: es ? 'Editar abertura' : 'Edit opening', exact: true }).click()
  await reopened.locator('#opening-offset').fill('')
  await save(reopened, es)
  await expect(reopened.locator('#opening-offset')).toHaveAttribute('aria-invalid', 'true')
  await reopened.getByRole('button', { name: es ? 'Cancelar' : 'Cancel', exact: true }).click()
  expect(JSON.parse(await savedJson(reopened))).toEqual(edited)
  await windowItem(reopened, es).click()
  await reopened.getByRole('button', { name: es ? 'Eliminar abertura' : 'Delete opening', exact: true }).click()
  await expect(windowItem(reopened, es)).toHaveCount(0)
  await reopened.reload()
  await reopened.getByRole('button', { name: /Aberturas/ }).click()
  await reopened.getByRole('button', { name: es ? 'Abrir plano 2D' : 'Open 2D plan', exact: true }).click()
  await expect(door(reopened, es)).toBeVisible()
  expect(JSON.parse(await savedJson(reopened)).openings).toEqual([edited.openings[0]])
  expect(errors).toEqual([])
})

test('reject wall, height and overlap errors; preserve drafts and saved data on write failures', async ({ page }, info) => {
  const es = info.project.name === 'phone'
  await page.addInitScript(() => {
    const put = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args) {
      if (this.name === 'projects' && sessionStorage.getItem('deny-put')) throw new DOMException('Full', 'QuotaExceededError')
      return put.apply(this, args)
    }
  })
  await openEditor(page, es)
  await doorForm(page, es)
  await save(page, es)
  await expect(door(page, es)).toBeVisible()
  const before = await savedJson(page)
  await doorForm(page, es)
  await page.locator('#opening-width').fill('10')
  await save(page, es)
  await expect(page.getByRole('alert')).toContainText(es ? 'deben caber en la pared' : 'must fit within the wall')
  await expect(page.locator('#opening-width')).toHaveValue('10')
  await page.locator('#opening-width').fill('1')
  await page.locator('#opening-height').fill('10')
  await save(page, es)
  await expect(page.getByRole('alert')).toContainText(es ? 'deben caber en la habitación' : 'must fit within the room')
  await page.locator('#opening-height').fill('2.1')
  await page.locator('#opening-offset').fill('0.6')
  await save(page, es)
  await expect(page.getByRole('alert')).toContainText(es ? 'se superpone' : 'overlaps another')
  expect(await savedJson(page)).toBe(before)
  await page.locator('#opening-offset').fill('2.5')
  await page.evaluate(() => sessionStorage.setItem('deny-put', 'yes'))
  await save(page, es)
  await expect(page.getByRole('alert')).toContainText(es ? 'No se pudo guardar' : 'Could not save')
  await expect(page.locator('#opening-offset')).toHaveValue('2.5')
  expect(await savedJson(page)).toBe(before)
  await page.evaluate(() => sessionStorage.removeItem('deny-put'))
  await save(page, es)
  await expect(door(page, es, 2)).toHaveAttribute('aria-pressed', 'true')
  expect(JSON.parse(await savedJson(page)).openings).toHaveLength(2)
  await page.evaluate(() => sessionStorage.setItem('deny-put', 'yes'))
  await page.getByRole('button', { name: es ? 'Eliminar abertura' : 'Delete opening', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText(es ? 'No se pudo guardar' : 'Could not save')
  await expect(door(page, es, 2)).toBeVisible()
  expect(JSON.parse(await savedJson(page)).openings).toHaveLength(2)
  await page.evaluate(() => sessionStorage.removeItem('deny-put'))
  await page.getByRole('button', { name: es ? 'Eliminar abertura' : 'Delete opening', exact: true }).click()
  await expect(door(page, es, 2)).toHaveCount(0)
  expect(JSON.parse(await savedJson(page)).openings).toHaveLength(1)
})
