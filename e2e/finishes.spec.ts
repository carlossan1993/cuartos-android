import { expect, test, type Page } from '@playwright/test'

async function openEditor(page: Page, es: boolean) {
  await page.goto('/')
  await page.getByRole('button', { name: es ? 'Crear un proyecto' : 'Create a project', exact: true }).click()
  await page.locator('#projectName').fill('Acabados')
  await page.locator('#roomName').fill('Dormitorio')
  await page.getByRole('button', { name: es ? 'Continuar' : 'Continue', exact: true }).click()
  await page.locator('#width').fill('4.2')
  await page.locator('#depth').fill('3.15')
  await page.getByRole('button', { name: es ? 'Crear y guardar' : 'Create and save', exact: true }).click()
  await page.getByRole('button', { name: es ? 'Abrir plano 2D' : 'Open 2D plan', exact: true }).click()
  await expect(page.locator('.canvas-surface canvas')).toBeVisible()
}
async function savedJson(page: Page): Promise<string> {
  return page.evaluate(() => new Promise<string>((resolve, reject) => {
    const request = indexedDB.open('cuartos-local')
    request.onerror = () => reject(request.error)
    request.onsuccess = () => {
      const db = request.result, read = db.transaction('projects').objectStore('projects').getAll()
      read.onsuccess = () => { db.close(); resolve(read.result[0].json) }
      read.onerror = () => { db.close(); reject(read.error) }
    }
  }))
}
const edit = (page: Page, es: boolean) => page.getByRole('button', { name: es ? 'Editar acabados' : 'Edit finishes', exact: true }).click()
const save = (page: Page, es: boolean) => page.getByRole('button', { name: es ? 'Guardar acabado' : 'Save finish', exact: true }).click()
const preset = (page: Page, name: string) => page.locator('.finish-presets').getByRole('button', { name, exact: true })
async function pixelAt(page: Page, point: { x: number; y: number }) {
  return page.locator('.canvas-surface canvas').evaluate((canvas: HTMLCanvasElement, point) => {
    const width = parseFloat(canvas.style.width), height = parseFloat(canvas.style.height)
    const pad = Math.min(64, width * .18, height * .18), scale = Math.min((width - 2 * pad) / 4.2, (height - 2 * pad) / 3.15)
    const x = width / 2 + (point.x - 2.1) * scale, y = height / 2 + (point.y - 1.575) * scale
    return Array.from(canvas.getContext('2d')!.getImageData(Math.floor(x * canvas.width / width), Math.floor(y * canvas.height / height), 1, 1).data).slice(0, 3)
  }, point)
}

test('apply floor and single-wall finishes, keep visible colors on selection, cancel and reopen offline', async ({ page, context }, info) => {
  const es = info.project.name === 'phone', errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await openEditor(page, es)
  await page.getByRole('button', { name: es ? 'Añadir puerta' : 'Add door', exact: true }).click()
  await expect(page.getByRole('button', { name: es ? 'Editar acabados' : 'Edit finishes', exact: true, includeHidden: true })).toBeDisabled()
  await page.getByRole('button', { name: es ? 'Guardar abertura' : 'Save opening', exact: true }).click()
  await expect(page.locator('.opening-form-panel')).toHaveCount(0)
  const original = await savedJson(page)
  await edit(page, es)
  await expect(page.getByRole('button', { name: es ? 'Añadir puerta' : 'Add door', exact: true, includeHidden: true })).toBeDisabled()
  await preset(page, es ? 'Roble' : 'Oak').click()
  await expect(page.locator('#finish-color')).toHaveValue('#c39a68')
  expect(await savedJson(page)).toBe(original)
  await page.locator('.finish-form').screenshot({ path: `test-results/finish-form-${info.project.name}.png` })
  await page.getByRole('button', { name: es ? 'Cancelar' : 'Cancel', exact: true }).click()
  expect(await savedJson(page)).toBe(original)
  await edit(page, es)
  await preset(page, es ? 'Roble' : 'Oak').click()
  await save(page, es)
  await expect(page.locator('.finish-form')).toHaveCount(0)
  await expect.poll(() => pixelAt(page, { x: 2.05, y: 2.25 })).toEqual([195, 154, 104])
  await page.getByRole('button', { name: es ? 'Quitar selección' : 'Clear selection', exact: true }).click()
  expect(await pixelAt(page, { x: 2.05, y: 2.25 })).toEqual([195, 154, 104])
  await edit(page, es)
  await page.locator('#finish-surface').selectOption({ index: 2 })
  await preset(page, es ? 'Azul profundo' : 'Deep blue').click()
  await save(page, es)
  await expect(page.locator('.finish-form')).toHaveCount(0)
  await expect.poll(() => pixelAt(page, { x: 2.7, y: 0 })).toEqual([3, 3, 140])
  const stored = JSON.parse(await savedJson(page)), initial = JSON.parse(original)
  expect(stored.rooms[0].floorMaterial).toEqual({ color: '#c39a68', textureId: 'floor-planks' })
  const wallIds = Object.keys(stored.rooms[0].wallMaterials)
  expect(stored.rooms[0].wallMaterials[wallIds[0]]).toEqual({ color: '#03038c' })
  for (const id of wallIds.slice(1)) expect(stored.rooms[0].wallMaterials[id]).toEqual(initial.rooms[0].wallMaterials[id])
  expect(stored.openings).toEqual(initial.openings)
  expect(stored.rooms[0].polygon).toEqual(initial.rooms[0].polygon)
  expect(stored.furniture).toEqual(initial.furniture)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `test-results/finishes-${info.project.name}.png`, fullPage: true })
  const reopened = await context.newPage()
  await page.close()
  await reopened.route('**/*', route => new URL(route.request().url()).origin === 'http://127.0.0.1:4173' ? route.continue() : route.abort())
  await reopened.goto('/')
  await reopened.getByRole('button', { name: /Acabados/ }).click()
  await reopened.getByRole('button', { name: es ? 'Abrir plano 2D' : 'Open 2D plan', exact: true }).click()
  await expect(reopened.locator('.finish-summary')).toContainText(es ? 'Roble' : 'Oak')
  await expect(reopened.locator('.finish-summary')).toContainText(es ? 'Azul profundo' : 'Deep blue')
  await expect.poll(() => pixelAt(reopened, { x: 2.05, y: 2.25 })).toEqual([195, 154, 104])
  expect(JSON.parse(await savedJson(reopened))).toEqual(stored)
  expect(errors).toEqual([])
})

test('validate custom colors, preserve drafts across language and write failures, then apply all walls', async ({ page }, info) => {
  const es = info.project.name === 'phone'
  await page.addInitScript(() => {
    const put = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args) {
      if (this.name === 'projects' && sessionStorage.getItem('deny-put')) throw new DOMException('Full', 'QuotaExceededError')
      return put.apply(this, args)
    }
  })
  await openEditor(page, es)
  const original = await savedJson(page)
  await edit(page, es)
  await page.locator('#finish-color').fill('#fff')
  await save(page, es)
  await expect(page.locator('#finish-color')).toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('#finish-color')).toBeFocused()
  expect(await savedJson(page)).toBe(original)
  await page.locator('#finish-color').fill('#123ABC')
  await page.locator('#finish-pattern').selectOption('floor-tiles')
  await page.getByRole('combobox', { name: es ? 'Idioma' : 'Language', exact: true }).selectOption(es ? 'en' : 'es')
  await expect(page.locator('#finish-color')).toHaveValue('#123abc')
  await expect(page.locator('#finish-pattern')).toHaveValue('floor-tiles')
  await page.getByRole('combobox', { name: es ? 'Language' : 'Idioma', exact: true }).selectOption(es ? 'es' : 'en')
  await page.evaluate(() => sessionStorage.setItem('deny-put', 'yes'))
  await save(page, es)
  await expect(page.getByRole('alert')).toContainText(es ? 'No se pudo guardar' : 'Could not save')
  await expect(page.locator('#finish-color')).toHaveValue('#123abc')
  expect(await savedJson(page)).toBe(original)
  await page.evaluate(() => sessionStorage.removeItem('deny-put'))
  await save(page, es)
  await expect(page.locator('.finish-form')).toHaveCount(0)
  expect(JSON.parse(await savedJson(page)).rooms[0].floorMaterial).toEqual({ color: '#123abc', textureId: 'floor-tiles' })
  await edit(page, es)
  await page.locator('#finish-surface').selectOption('allWalls')
  await preset(page, es ? 'Verde salvia' : 'Sage green').click()
  await save(page, es)
  await expect(page.locator('.finish-form')).toHaveCount(0)
  const stored = JSON.parse(await savedJson(page))
  expect(Object.values(stored.rooms[0].wallMaterials)).toEqual(Array(4).fill({ color: '#718571' }))
  expect(stored.rooms[0].floorMaterial).toEqual({ color: '#123abc', textureId: 'floor-tiles' })
  await edit(page, es)
  await page.locator('#finish-surface').selectOption({ index: 2 })
  await preset(page, es ? 'Terracota' : 'Terracotta').click()
  await page.getByRole('button', { name: es ? 'Cancelar' : 'Cancel', exact: true }).click()
  expect(JSON.parse(await savedJson(page))).toEqual(stored)
})
