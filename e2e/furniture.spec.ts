import { expect, test, type Page } from '@playwright/test'

async function openEditor(page: Page, es: boolean) {
  await page.addInitScript(() => {
    const put = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args) {
      if (this.name === 'projects' && sessionStorage.getItem('deny-put')) throw new DOMException('Full', 'QuotaExceededError')
      return put.apply(this, args)
    }
  })
  await page.goto('/')
  await page.getByRole('button', { name: es ? 'Crear un proyecto' : 'Create a project', exact: true }).click()
  await page.locator('#projectName').fill('Muebles')
  await page.locator('#roomName').fill('Dormitorio')
  await page.getByRole('button', { name: es ? 'Continuar' : 'Continue', exact: true }).click()
  await page.locator('#width').fill('4.2')
  await page.locator('#depth').fill('3.15')
  await page.getByRole('button', { name: es ? 'Crear y guardar' : 'Create and save', exact: true }).click()
  await page.getByRole('button', { name: es ? 'Abrir plano 2D' : 'Open 2D plan', exact: true }).click()
  await expect(page.locator('.canvas-surface canvas')).toBeVisible()
}
async function savedJson(page: Page): Promise<string> {
  return page.evaluate(() => new Promise<string>((resolve, reject) => {
    const request = indexedDB.open('cuartos-local')
    request.onerror = () => reject(request.error)
    request.onsuccess = () => {
      const db = request.result, read = db.transaction('projects').objectStore('projects').getAll()
      read.onsuccess = () => { db.close(); resolve(read.result[0].json) }
      read.onerror = () => { db.close(); reject(read.error) }
    }
  }))
}
async function stored(page: Page) { return JSON.parse(await savedJson(page)) }
const button = (page: Page, es: boolean, esName: string, enName: string) => page.getByRole('button', { name: es ? esName : enName, exact: true })
async function add(page: Page, es: boolean, name: string) {
  await button(page, es, 'Abrir catálogo', 'Open catalog').click()
  await page.locator('.furniture-catalog-card').filter({ has: page.getByText(name, { exact: true }) }).click()
  await button(page, es, 'Añadir mueble', 'Add furniture').click()
  await expect(page.locator('#furniture-catalog-title')).toHaveCount(0)
}
async function coordinates(page: Page, world: { x: number; y: number }) {
  const surface = page.locator('.canvas-surface')
  await surface.scrollIntoViewIfNeeded()
  const box = (await surface.boundingBox())!, width = Math.round(box.width), height = Math.round(box.height)
  const pad = Math.min(64, width * .18, height * .18), scale = Math.min((width - 2 * pad) / 4.2, (height - 2 * pad) / 3.15)
  return { x: box.x + width / 2 + (world.x - 2.1) * scale, y: box.y + height / 2 + (world.y - 1.575) * scale }
}
async function mouseDrag(page: Page, from: { x: number; y: number }, to: { x: number; y: number }) {
  const a = await coordinates(page, from), b = await coordinates(page, to)
  await page.mouse.move(a.x, a.y); await page.mouse.down()
  await page.mouse.move(b.x, b.y, { steps: 5 }); await page.mouse.up()
}
const list = (page: Page) => page.locator('.furniture-list button')

test('catalog, snapped mouse drag, rotation, duplicate, precise inputs, failed save and reopen', async ({ page, context }, info) => {
  const es = info.project.name === 'phone', errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await openEditor(page, es)
  await button(page, es, 'Añadir puerta', 'Add door').click()
  await button(page, es, 'Guardar abertura', 'Save opening').click()
  await expect(page.locator('.opening-form-panel')).toHaveCount(0)
  await button(page, es, 'Editar acabados', 'Edit finishes').click()
  await page.locator('.finish-presets button').filter({ hasText: es ? 'Roble' : 'Oak' }).click()
  await button(page, es, 'Guardar acabado', 'Save finish').click()
  await expect(page.locator('.finish-form')).toHaveCount(0)
  const before = await stored(page)
  await button(page, es, 'Abrir catálogo', 'Open catalog').click()
  await expect(page.locator('.furniture-catalog-card')).toHaveCount(16)
  await expect(page.getByRole('button', { name: es ? 'Editar acabados' : 'Edit finishes', exact: true, includeHidden: true })).toBeDisabled()
  await page.locator('.furniture-panel').screenshot({ path: `test-results/furniture-catalog-${info.project.name}.png` })
  await button(page, es, 'Añadir mueble', 'Add furniture').click()
  await expect(list(page)).toHaveCount(1)
  await expect.poll(async () => (await stored(page)).furniture[0].position).toEqual({ x: 2.1, y: 1.6 })
  await mouseDrag(page, { x: 2.1, y: 1.6 }, { x: 1.3, y: 1.3 })
  await expect.poll(async () => (await stored(page)).furniture[0].position).toEqual({ x: 1.3, y: 1.3 })
  await button(page, es, 'Girar 90°', 'Rotate 90°').click()
  await expect.poll(async () => (await stored(page)).furniture[0].rotation).toBe(90)
  await button(page, es, 'Duplicar', 'Duplicate').click()
  await expect(list(page)).toHaveCount(2)
  const copyId = (await stored(page)).furniture[1].id
  expect(copyId).not.toBe((await stored(page)).furniture[0].id)
  await page.getByRole('checkbox', { name: es ? /^Ajuste:/ : /^Snap:/ }).uncheck()
  await button(page, es, 'Editar posición', 'Edit position').click()
  await page.locator('#furniture-unit').selectOption('cm')
  await page.locator('#furniture-x').fill('0')
  await button(page, es, 'Guardar posición', 'Save position').click()
  await expect(page.getByRole('alert')).toContainText(es ? 'base completa' : 'entire furniture footprint')
  await page.locator('#furniture-x').fill('320,25')
  await page.locator('#furniture-y').fill('230.5')
  await page.locator('#furniture-rotation').fill('-90')
  await page.getByRole('combobox', { name: es ? 'Idioma' : 'Language', exact: true }).selectOption(es ? 'en' : 'es')
  await expect(page.locator('#furniture-x')).toHaveValue('320,25')
  await page.getByRole('combobox', { name: es ? 'Language' : 'Idioma', exact: true }).selectOption(es ? 'es' : 'en')
  const old = await savedJson(page)
  await page.evaluate(() => sessionStorage.setItem('deny-put', 'yes'))
  await button(page, es, 'Guardar posición', 'Save position').click()
  await expect(page.getByRole('alert')).toContainText(es ? 'No se pudo guardar' : 'Could not save')
  await expect(page.locator('#furniture-x')).toHaveValue('320,25')
  expect(await savedJson(page)).toBe(old)
  await page.evaluate(() => sessionStorage.removeItem('deny-put'))
  await page.locator('.furniture-panel').screenshot({ path: `test-results/furniture-position-${info.project.name}.png` })
  await button(page, es, 'Guardar posición', 'Save position').click()
  await expect(page.locator('#furniture-position-title')).toHaveCount(0)
  expect((await stored(page)).furniture[1]).toMatchObject({ id: copyId, position: { x: 3.2025, y: 2.305 }, rotation: 270 })
  await add(page, es, es ? 'Silla' : 'Chair')
  await button(page, es, 'Editar posición', 'Edit position').click()
  await page.locator('#furniture-x').fill('2.8'); await page.locator('#furniture-y').fill('0.5')
  await button(page, es, 'Guardar posición', 'Save position').click()
  await expect(page.locator('#furniture-position-title')).toHaveCount(0)
  await list(page).nth(1).click()
  const saved = await stored(page)
  expect(saved.rooms).toEqual(before.rooms); expect(saved.openings).toEqual(before.openings)
  expect(saved.furniture).toHaveLength(3)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `test-results/furniture-${info.project.name}.png`, fullPage: true })
  await button(page, es, 'Editar posición', 'Edit position').click()
  await page.locator('#furniture-x').fill('')
  await button(page, es, 'Guardar posición', 'Save position').click()
  await expect(page.locator('#furniture-x')).toHaveAttribute('aria-invalid', 'true')
  await button(page, es, 'Cancelar', 'Cancel').click()
  expect((await stored(page)).furniture).toEqual(saved.furniture)
  const reopened = await context.newPage()
  await page.close()
  await reopened.route('**/*', route => new URL(route.request().url()).origin === 'http://127.0.0.1:4173' ? route.continue() : route.abort())
  await reopened.goto('/')
  await reopened.getByRole('button', { name: /Muebles/ }).click()
  await button(reopened, es, 'Abrir plano 2D', 'Open 2D plan').click()
  await expect(list(reopened)).toHaveCount(3)
  expect(await stored(reopened)).toEqual(saved)
  await list(reopened).nth(2).click()
  await button(reopened, es, 'Eliminar mueble', 'Delete furniture').click()
  await expect(list(reopened)).toHaveCount(2)
  expect((await stored(reopened)).furniture).toEqual(saved.furniture.slice(0, 2))
  expect(errors).toEqual([])
})

test('touch preview, cancellation, pinch, orientation, failed drag retry and invalid drop', async ({ page, context }, info) => {
  const es = info.project.name === 'phone'
  await openEditor(page, es)
  await add(page, es, es ? 'Silla' : 'Chair')
  const client = await context.newCDPSession(page)
  await client.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 2 })
  const touch = async (type: 'touchStart' | 'touchMove' | 'touchEnd' | 'touchCancel', points: { x: number; y: number; id: number }[]) => { await client.send('Input.dispatchTouchEvent', { type, touchPoints: points }) }
  async function begin(from: { x: number; y: number }, to: { x: number; y: number }) {
    const a = await coordinates(page, from), b = await coordinates(page, to)
    await touch('touchStart', [{ ...a, id: 1 }]); await touch('touchMove', [{ ...b, id: 1 }])
    return { a, b }
  }
  let original = await savedJson(page)
  const tap = await coordinates(page, { x: 2.1, y: 1.6 })
  await touch('touchStart', [{ ...tap, id: 1 }]); await touch('touchEnd', [])
  expect(await savedJson(page)).toBe(original)
  await begin({ x: 2.1, y: 1.6 }, { x: 2.46, y: 1.84 })
  expect(await savedJson(page)).toBe(original)
  await touch('touchEnd', [])
  await expect.poll(async () => (await stored(page)).furniture[0].position).toEqual({ x: 2.5, y: 1.8 })
  original = await savedJson(page)
  await begin({ x: 2.5, y: 1.8 }, { x: 3, y: 2.2 }); await touch('touchCancel', [])
  expect(await savedJson(page)).toBe(original)
  const a = await coordinates(page, { x: 2.5, y: 1.8 })
  await touch('touchStart', [{ ...a, id: 1 }])
  await touch('touchStart', [{ ...a, id: 1 }, { x: a.x + 35, y: a.y, id: 2 }])
  await touch('touchMove', [{ x: a.x - 20, y: a.y, id: 1 }, { x: a.x + 65, y: a.y, id: 2 }])
  await touch('touchEnd', [])
  await expect.poll(async () => parseInt((await page.getByLabel(es ? 'Nivel de zoom' : 'Zoom level', { exact: true }).textContent())!)).toBeGreaterThan(150)
  expect(await savedJson(page)).toBe(original)
  await button(page, es, 'Encuadrar', 'Fit room').click()
  await begin({ x: 2.5, y: 1.8 }, { x: 3, y: 2.2 })
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await touch('touchCancel', [])
  expect(await savedJson(page)).toBe(original)
  await begin({ x: 2.5, y: 1.8 }, { x: 3, y: 2.2 })
  await page.setViewportSize(es ? { width: 844, height: 390 } : { width: 768, height: 1024 })
  await expect(page.getByRole('button', { name: es ? /Volver al resumen/ : /Back to summary/ })).toBeEnabled()
  await touch('touchCancel', [])
  expect(await savedJson(page)).toBe(original)
  await page.setViewportSize(es ? { width: 393, height: 727 } : { width: 1024, height: 768 })
  await button(page, es, 'Encuadrar', 'Fit room').click()
  const m1 = await coordinates(page, { x: 2.5, y: 1.8 }), m2 = await coordinates(page, { x: 3, y: 2.2 })
  await page.mouse.move(m1.x, m1.y); await page.mouse.down(); await page.mouse.move(m2.x, m2.y, { steps: 4 })
  await page.locator('.canvas-surface').press('Escape'); await page.mouse.up()
  expect(await savedJson(page)).toBe(original)
  await page.evaluate(() => sessionStorage.setItem('deny-put', 'yes'))
  await begin({ x: 2.5, y: 1.8 }, { x: 1.4, y: 1.1 }); await touch('touchEnd', [])
  await expect(page.getByRole('alert')).toContainText(es ? 'No se pudo guardar' : 'Could not save')
  expect(await savedJson(page)).toBe(original)
  await page.evaluate(() => sessionStorage.removeItem('deny-put'))
  await button(page, es, 'Reintentar cambio', 'Retry change').click()
  await expect.poll(async () => (await stored(page)).furniture[0].position).toEqual({ x: 1.4, y: 1.1 })
  expect((await stored(page)).furniture).toHaveLength(1)
  original = await savedJson(page)
  await begin({ x: 1.4, y: 1.1 }, { x: .02, y: .02 }); await touch('touchEnd', [])
  await expect(page.getByRole('alert')).toContainText(es ? 'base completa' : 'entire furniture footprint')
  expect(await savedJson(page)).toBe(original)
  await client.detach()
})
