import { expect, test, type Page } from '@playwright/test'

const button = (page: Page, es: boolean, spanish: string, english: string) => page.getByRole('button', { name: es ? spanish : english, exact: true })
async function savedJson(page: Page): Promise<string> {
  return page.evaluate(() => new Promise<string>((resolve, reject) => {
    const request = indexedDB.open('cuartos-local')
    request.onerror = () => reject(request.error)
    request.onsuccess = () => {
      const db = request.result, read = db.transaction('projects').objectStore('projects').getAll()
      read.onsuccess = () => { db.close(); resolve(read.result[0]?.json ?? '') }; read.onerror = () => { db.close(); reject(read.error) }
    }
  }))
}
async function start(page: Page, es: boolean, shape: string) {
  await page.route('**/*', route => new URL(route.request().url()).origin === 'http://127.0.0.1:4173' ? route.continue() : route.abort())
  await page.goto('/')
  await button(page, es, 'Crear un proyecto', 'Create a project').click()
  await page.locator('#projectName').fill(shape === 'l' ? 'Mi habitación L' : 'Dos ambientes')
  await page.locator(`input[name="shape"][value="${shape}"]`).check()
  await page.locator('#roomName').fill('Sala')
}
async function open3D(page: Page, es: boolean) {
  await button(page, es, 'Ver habitación 3D', 'View room in 3D').click()
  await expect(page.locator('.viewer-canvas')).toHaveAttribute('data-ready', 'true', { timeout: 20000 })
}
async function finish(page: Page, es: boolean, preset: string, surface = 'floor') {
  await button(page, es, 'Editar acabados', 'Edit finishes').click()
  if (surface !== 'floor') await page.locator('#finish-surface').selectOption({ index: Number(surface) })
  await page.locator('.finish-presets button').filter({ hasText: preset }).click()
  await button(page, es, 'Guardar acabado', 'Save finish').click()
  await expect(page.locator('.finish-form')).toHaveCount(0)
}

test('create L in cm, correct cutouts, retry save, use concave placement and reopen 2D/3D', async ({ page }, info) => {
  const es = info.project.name === 'phone', errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    const add = IDBObjectStore.prototype.add
    IDBObjectStore.prototype.add = function (...args) { if (this.name === 'projects' && sessionStorage.getItem('deny-add')) throw new DOMException('Full', 'QuotaExceededError'); return add.apply(this, args) }
  })
  await start(page, es, 'l')
  await button(page, es, 'Continuar', 'Continue').click()
  await page.locator('input[name="unit"][value="cm"]').check()
  await page.locator('#width').fill('420'); await page.locator('#depth').fill('315')
  await page.locator('#cutWidth').fill('420'); await page.locator('#cutDepth').fill('180')
  await button(page, es, 'Crear y guardar', 'Create and save').click()
  await expect(page.locator('#cutWidth')).toHaveAttribute('aria-invalid', 'true')
  expect(await savedJson(page)).toBe('')
  await page.locator('#cutWidth').fill('240')
  await page.getByRole('combobox', { name: es ? 'Idioma' : 'Language', exact: true }).selectOption(es ? 'en' : 'es')
  await expect(page.locator('#cutDepth')).toHaveValue('180')
  await page.getByRole('combobox', { name: es ? 'Language' : 'Idioma', exact: true }).selectOption(es ? 'es' : 'en')
  await button(page, es, 'Atrás', 'Back').click()
  await expect(page.locator('input[name="shape"][value="l"]')).toBeChecked()
  await button(page, es, 'Continuar', 'Continue').click()
  await expect(page.locator('#cutWidth')).toHaveValue('240')
  await page.screenshot({ path: `test-results/layout-l-wizard-${info.project.name}.png`, fullPage: true })
  await page.evaluate(() => sessionStorage.setItem('deny-add', 'yes'))
  await button(page, es, 'Crear y guardar', 'Create and save').click()
  await expect(page.getByRole('alert')).toContainText(es ? 'No se pudo guardar' : 'Could not save')
  expect(await savedJson(page)).toBe('')
  await page.evaluate(() => sessionStorage.removeItem('deny-add'))
  await button(page, es, 'Crear y guardar', 'Create and save').click()
  await expect(page.locator('.summary-room')).toHaveCount(1)
  await expect(page.locator('.room-measures')).toContainText(es ? '8,91 m²' : '8.91 m²')
  expect(JSON.parse(await savedJson(page)).rooms[0].polygon).toHaveLength(6)
  await button(page, es, 'Abrir plano 2D', 'Open 2D plan').click()
  await finish(page, es, es ? 'Roble' : 'Oak')
  await finish(page, es, es ? 'Azul profundo' : 'Deep blue', '2')
  await button(page, es, 'Añadir ventana', 'Add window').click()
  await expect(page.locator('#opening-wallId option')).toHaveCount(6)
  await page.locator('#opening-wallId').selectOption({ index: 3 })
  await button(page, es, 'Guardar abertura', 'Save opening').click()
  await expect(page.locator('.opening-form-panel')).toHaveCount(0)
  await button(page, es, 'Abrir catálogo', 'Open catalog').click()
  await page.locator('.furniture-catalog-card').nth(4).click()
  await button(page, es, 'Añadir mueble', 'Add furniture').click()
  await expect(page.locator('#furniture-catalog-title')).toHaveCount(0)
  await button(page, es, 'Editar posición', 'Edit position').click()
  await page.locator('#furniture-x').fill('3'); await page.locator('#furniture-y').fill('2.4')
  await button(page, es, 'Guardar posición', 'Save position').click()
  await expect(page.getByRole('alert')).toContainText(es ? 'base completa' : 'entire furniture footprint')
  await page.locator('#furniture-x').fill('1')
  await button(page, es, 'Guardar posición', 'Save position').click()
  await expect(page.locator('#furniture-position-title')).toHaveCount(0)
  const saved = await savedJson(page)
  await page.screenshot({ path: `test-results/layout-l-plan-${info.project.name}.png`, fullPage: true })
  await open3D(page, es)
  await page.screenshot({ path: `test-results/layout-l-3d-${info.project.name}.png`, fullPage: true })
  await button(page, es, 'Desde arriba', 'Top view').click()
  await page.locator('.viewer-canvas').screenshot({ path: `test-results/layout-l-top-${info.project.name}.png` })
  await page.getByRole('checkbox', { name: es ? 'Vista abierta' : 'Cutaway view', exact: true }).uncheck()
  await page.locator('.viewer-canvas').screenshot({ path: `test-results/layout-l-complete-${info.project.name}.png` })
  expect(await savedJson(page)).toBe(saved)
  await page.reload(); await page.getByRole('button', { name: /Mi habitación L/ }).click()
  await expect(page.locator('.summary-room')).toContainText('Sala')
  await button(page, es, 'Abrir plano 2D', 'Open 2D plan').click(); await open3D(page, es)
  expect(await savedJson(page)).toBe(saved)
  expect(errors).toEqual([])
})

for (const orientation of ['right', 'below']) test(`two connected spaces ${orientation} preserve rooms, open passage and independent finishes`, async ({ page }, info) => {
  const es = info.project.name === 'phone', errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await start(page, es, 'connected')
  await button(page, es, 'Continuar', 'Continue').click()
  await expect(page.locator('#room2Name')).toHaveAttribute('aria-invalid', 'true')
  await page.locator('#room2Name').fill('Estudio')
  await button(page, es, 'Continuar', 'Continue').click()
  await page.locator('#width').fill('4.2'); await page.locator('#depth').fill('3.15')
  await page.locator('#width2').fill('3'); await page.locator('#depth2').fill('2.4')
  await page.locator('#layout-orientation').selectOption(orientation)
  await page.screenshot({ path: `test-results/layout-${orientation}-wizard-${info.project.name}.png`, fullPage: true })
  await button(page, es, 'Crear y guardar', 'Create and save').click()
  await expect(page.locator('.summary-room')).toHaveCount(2)
  await expect(page.locator('.connection-summary')).toContainText(orientation === 'right' ? es ? '2,4 m' : '2.4 m' : '3 m')
  const initial = JSON.parse(await savedJson(page))
  expect(initial.rooms).toHaveLength(2)
  expect(initial.rooms[1].polygon[0]).toMatchObject(orientation === 'right' ? { x: 4.2, y: 0 } : { x: 0, y: 3.15 })
  await button(page, es, 'Abrir plano 2D', 'Open 2D plan').click()
  await expect(page.locator('.editor-room-list button')).toHaveCount(2)
  await page.locator('.editor-room-list button').first().click()
  await finish(page, es, es ? 'Roble' : 'Oak')
  await finish(page, es, es ? 'Azul profundo' : 'Deep blue', '2')
  await button(page, es, 'Añadir puerta', 'Add door').click()
  await page.locator('#opening-wallId').selectOption({ index: orientation === 'right' ? 1 : 2 })
  await page.locator('#opening-offset').fill(orientation === 'right' ? '.3' : '2')
  await page.locator('#opening-width').fill('.8')
  await button(page, es, 'Guardar abertura', 'Save opening').click()
  await expect(page.getByRole('alert')).toContainText(es ? 'paso abierto' : 'open passage')
  await button(page, es, 'Cancelar', 'Cancel').click()
  await page.locator('.editor-room-list button').nth(1).click()
  await finish(page, es, es ? 'Porcelanato' : 'Porcelain tile')
  await button(page, es, 'Añadir ventana', 'Add window').click()
  await expect(page.locator('#opening-wallId option:disabled')).toHaveCount(1)
  await button(page, es, 'Guardar abertura', 'Save opening').click()
  await expect(page.locator('.opening-form-panel')).toHaveCount(0)
  await button(page, es, 'Abrir catálogo', 'Open catalog').click()
  await page.locator('.furniture-catalog-card').nth(6).click()
  await button(page, es, 'Añadir mueble', 'Add furniture').click()
  await expect(page.locator('#furniture-catalog-title')).toHaveCount(0)
  const saved = await savedJson(page), p = JSON.parse(saved)
  expect(p.furniture[0].roomId).toBe(p.rooms[1].id)
  expect(p.rooms[0].floorMaterial.textureId).toBe('floor-planks')
  expect(p.rooms[1].floorMaterial.textureId).toBe('floor-tiles')
  expect(p.schemaVersion).toBe(1)
  await page.screenshot({ path: `test-results/layout-${orientation}-plan-${info.project.name}.png`, fullPage: true })
  await open3D(page, es)
  await expect(page.locator('.viewer-room')).toHaveCount(2)
  await page.screenshot({ path: `test-results/layout-${orientation}-3d-${info.project.name}.png`, fullPage: true })
  await button(page, es, 'Desde arriba', 'Top view').click()
  await page.locator('.viewer-canvas').screenshot({ path: `test-results/layout-${orientation}-top-${info.project.name}.png` })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.reload(); await page.getByRole('button', { name: /Dos ambientes/ }).click()
  await expect(page.locator('.summary-room')).toHaveCount(2)
  await button(page, es, 'Abrir plano 2D', 'Open 2D plan').click(); await open3D(page, es)
  expect(await savedJson(page)).toBe(saved)
  expect(errors).toEqual([])
})
