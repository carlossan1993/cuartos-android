import { expect, test } from '@playwright/test'
import { mkdir, readFile } from 'node:fs/promises'
import { button, createDesign, design, records, saved } from './support/qa-flow.ts'

for (const shape of ['rectangle', 'l', 'connected'] as const) test(`bilingual design and portable files: ${shape}`, async ({ page }, info) => {
  test.setTimeout(90000)
  const es = info.project.use.locale?.startsWith('es') ?? false, name = `QA ${shape}`, errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => new URL(route.request().url()).origin === 'http://127.0.0.1:4173' ? route.continue() : route.abort())
  await page.goto('/')
  const original = await createDesign(page, es, shape, name)
  await button(page, es, 'Girar 90°', 'Rotate 90°').click()
  await expect.poll(async () => (await saved(page, name)).furniture[0].rotation).toBe(90)
  await button(page, es, 'Deshacer', 'Undo').click()
  await expect.poll(async () => design(await saved(page, name))).toEqual(design(original))
  await button(page, es, 'Rehacer', 'Redo').click()
  await expect.poll(async () => (await saved(page, name)).furniture[0].rotation).toBe(90)
  const confirmed = await saved(page, name)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await mkdir('test-results', { recursive: true })
  await page.screenshot({ path: `test-results/qa-plan-${info.project.name}-${shape}.png`, fullPage: true })
  await button(page, es, 'Ver habitación 3D', 'View room in 3D').click()
  await expect(page.locator('.viewer-canvas')).toHaveAttribute('data-ready', 'true', { timeout: 30000 })
  await expect(page.locator('.viewer-inventory summary').first()).toContainText(es ? 'Muebles' : 'Furniture')
  await button(page, es, 'Desde arriba', 'Top view').click()
  await page.getByRole('checkbox', { name: es ? 'Vista abierta' : 'Cutaway view', exact: true }).uncheck()
  await page.getByRole('checkbox', { name: es ? 'Vista abierta' : 'Cutaway view', exact: true }).check()
  await page.screenshot({ path: `test-results/qa-3d-${info.project.name}-${shape}.png`, fullPage: true })
  expect(design(await saved(page, name))).toEqual(design(confirmed))
  await page.getByRole('button', { name: es ? /Volver al plano 2D/ : /Back to 2D plan/ }).click()
  await page.getByRole('button', { name: es ? /Volver al resumen/ : /Back to summary/ }).click()
  const download = page.waitForEvent('download')
  await button(page, es, 'Descargar archivo', 'Download file').click()
  const json = await readFile((await (await download).path())!)
  expect(JSON.parse(json.toString())).toEqual(confirmed)
  await page.locator('#export-format').selectOption('png'); await page.locator('#export-resolution').selectOption('1024')
  const pngDownload = page.waitForEvent('download')
  await button(page, es, 'Descargar archivo', 'Download file').click()
  const png = await readFile((await (await pngDownload).path())!)
  expect([png.readUInt32BE(16), png.readUInt32BE(20)]).toEqual([1024, 768])
  await page.getByRole('button', { name: es ? /Volver a tus proyectos/ : /Back to your projects/ }).click()
  await button(page, es, 'Importar proyecto', 'Import a project').click()
  await page.locator('#import-project-file').setInputFiles({ name: 'qa.json', mimeType: 'application/json', buffer: json })
  await page.locator('#import-project-name').fill('Copia QA')
  await button(page, es, 'Importar como copia', 'Import as a copy').click()
  await expect(page.getByRole('heading', { name: 'Copia QA', exact: true })).toBeVisible()
  expect((await records(page)).find(record => record.id === confirmed.id)?.json).toBe(JSON.stringify(confirmed))
  await page.reload()
  await page.getByRole('button', { name: `${es ? 'Abrir proyecto' : 'Open project'}: ${name}`, exact: true }).click()
  await button(page, es, 'Abrir plano 2D', 'Open 2D plan').click()
  await expect(page.locator('.canvas-surface canvas')).toBeVisible()
  await expect(button(page, es, 'Deshacer', 'Undo')).toBeDisabled()
  expect(await saved(page, name)).toEqual(confirmed)
  expect(errors).toEqual([])
})
